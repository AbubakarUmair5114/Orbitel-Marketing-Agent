def validate_dataset():
    total = len(records)
    assert total == 21, f"Expected 21 records, got {total}"

    pos = sum(1 for r in records if r["sentiment"] == "positive")
    neg = sum(1 for r in records if r["sentiment"] == "negative")
    neu = sum(1 for r in records if r["sentiment"] == "neutral")
    churn = sum(1 for r in records if r["churn_risk"] is True)
    conf_sum = sum(r["confidence_score"] for r in records)
    avg_conf = round(conf_sum / total, 2)

    pos_pct = round((pos / total) * 100, 1)
    neg_pct = round((neg / total) * 100, 1)
    neu_pct = round((neu / total) * 100, 2)
    churn_pct = round((churn / total) * 100, 1)

    print(f"Total Records: {total}")
    print(f"Positive: {pos} ({pos_pct}%) - Expected: 7 (33.3%)")
    print(f"Negative: {neg} ({neg_pct}%) - Expected: 11 (52.4%)")
    print(f"Neutral: {neu} ({neu_pct}%) - Expected: 3 (14.29%)")
    print(f"Churn Risk TRUE: {churn} ({churn_pct}%) - Expected: 10 (47.6%)")
    print(f"Avg Confidence Score: {avg_conf:.2f} - Expected: 0.89")

    assert pos == 7 and pos_pct == 33.3, "Positive count mismatch"
    assert neg == 11 and neg_pct == 52.4, "Negative count mismatch"
    assert neu == 3, "Neutral count mismatch"
    assert churn == 10 and churn_pct == 47.6, "Churn risk mismatch"
    assert avg_conf == 0.89, f"Avg confidence score mismatch: {avg_conf}"

    # Department distribution of churn risk records
    dept_churn = {}
    for r in records:
        if r["churn_risk"]:
            dept_churn[r["target_department"]] = dept_churn.get(r["target_department"], 0) + 1
    print("Churn Risk by Department:", dept_churn)
    assert dept_churn.get("operations", 0) >= dept_churn.get("finance", 0) >= dept_churn.get("marketing", 0), "Operations must lead churn risk"

    # Value segment distribution excluding unknown
    val_churn = {}
    for r in records:
        seg = r["customer_value_segment"]
        if seg not in val_churn:
            val_churn[seg] = {"High Risk": 0, "Low Risk": 0}
        if r["churn_risk"]:
            val_churn[seg]["High Risk"] += 1
        else:
            val_churn[seg]["Low Risk"] += 1
    print("Value Segments Breakdown:", val_churn)

    print("ALL VALIDATION CHECKS PASSED PERFECTLY!")

def export_files():
    base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    data_dir = os.path.join(base_dir, "data")
    os.makedirs(data_dir, exist_ok=True)

    json_path = os.path.join(data_dir, "orbitel_master_dataset_21_records.json")
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(records, f, indent=2)
    print(f"Exported JSON to {json_path}")

    csv_path = os.path.join(data_dir, "orbitel_master_dataset_21_records.csv")
    fields = list(records[0].keys())
    with open(csv_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        writer.writerows(records)
    print(f"Exported CSV to {csv_path}")

